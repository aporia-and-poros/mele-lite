/// 发什么、发给谁、为什么，请用户点同意。没同意：聊天、语音、通话、TA 主动打来都先停着，想用时再问。
/// 第一次发给某一家时那张「发到哪里」（LiteConsent）照旧再问一次。
enum AIConsent {
    static let key = "aiConsent.general.v1"
    static var granted: Bool { UserDefaults.standard.bool(forKey: key) }
    static func grant() { UserDefaults.standard.set(true, forKey: key) }
    static func revoke() {
        UserDefaults.standard.set(false, forKey: key)
        LiteConsent.book.revokeAll()
    }
}

