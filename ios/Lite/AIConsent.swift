/// Me → 隐私：看说明、收回 / 重新同意（AIConsentSheet 里说了「随时可以在 Me → 隐私 收回」）
struct PrivacyCard: View {
    @EnvironmentObject private var theme: AppTheme
    @AppStorage(AIConsent.key) private var agreed = false
    @State private var showSheet = false
    @State private var confirmRevoke = false

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            Text("隐私").font(Typo.sans(Typo.Size.headline, .semibold)).foregroundStyle(theme.ink)
            Text(agreed ? "已同意把聊天需要的数据发给第三方 AI 服务。" : "还没同意：聊天、语音和通话停用中。")
                .font(Typo.sans(Typo.Size.body)).foregroundStyle(theme.inkDim)
                .fixedSize(horizontal: false, vertical: true)
            Button { showSheet = true } label: {
                HStack {
                    Text(agreed ? "数据会发给谁" : "查看并同意").font(Typo.sans(Typo.Size.body)).foregroundStyle(theme.ink)
                    Spacer()
                    Image(systemName: "chevron.right").font(Typo.icon(12)).foregroundStyle(theme.inkFaint)
                }
                .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            if agreed {
                Button("收回同意") { confirmRevoke = true }
                    .font(Typo.sans(Typo.Size.body)).foregroundStyle(theme.accentDeep)
            }
        }
        .padding(16)
        .frame(maxWidth: .infinity, alignment: .leading)
        .cardSurface()
        .sheet(isPresented: $showSheet) {
            AIConsentSheet(onAgree: { AIConsent.grant(); agreed = true; showSheet = false },
                           onDecline: { if agreed { AIConsent.revoke(); agreed = false }; showSheet = false })
                .environmentObject(theme)
        }
        .confirmationDialog("收回同意？", isPresented: $confirmRevoke, titleVisibility: .visible) {
            Button("收回", role: .destructive) { AIConsent.revoke(); agreed = false }
        } message: {
            Text("收回以后不会再把数据发给第三方 AI，聊天、语音和通话会停用，直到你再同意。")
        }
    }
}
